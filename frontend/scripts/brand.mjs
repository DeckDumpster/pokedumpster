// Derives every favicon from the header's brand art, src/lib/components/Pokeball.svelte.
// Pure Node, no dependencies: a supersampled rasteriser for the mark's three
// primitives (stroked circle, stroked line) and a zlib PNG encoder.
//   node scripts/brand.mjs          write static/{favicon.svg,favicon-32.png,apple-touch-icon.png}
//   node scripts/brand.mjs --check  exit 1 if the committed files differ
import { readFileSync, writeFileSync } from 'node:fs';
import { deflateSync } from 'node:zlib';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

export function shapes(svelte) {
	const body = svelte.match(/<svg[\s\S]*?>([\s\S]*?)<\/svg>/)[1];
	return [...body.matchAll(/<(circle|line)\b([^>]*?)\/>/g)].map(([tag, kind, attrs]) => ({
		tag: tag.replace(/\s+/g, ' '),
		kind,
		a: Object.fromEntries([...attrs.matchAll(/([\w-]+)="([^"]*)"/g)].map((m) => [m[1], +m[2] || m[2]]))
	}));
}

export function readTheme() {
	const t = readFileSync(join(root, 'src/lib/styles/tokens.css'), 'utf8');
	const hex = (n) => t.match(new RegExp(`--${n}:\\s*(#[0-9a-fA-F]{6})\\s*;`))[1];
	return { crimson: hex('pd-crimson-500'), ink: hex('pd-ink-800') };
}

export function svg(shapeList, crimson) {
	const els = shapeList.map((s) => '\t' + s.tag.replace(/\s*\/>$/, ' />')).join('\n');
	return `<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="${crimson}" stroke-width="2">
	<title>PokeDumpster</title>
	<!-- Generated by scripts/brand.mjs from the shapes in src/lib/components/Pokeball.svelte. Do not edit: change the header art and re-run. -->
${els}
</svg>
`;
}

const rgb = (h) => [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16));

// Distance-field coverage of the mark at point (x,y) in the 24-unit box.
function covered(shapeList, x, y) {
	for (const { kind, a } of shapeList) {
		const hw = (a['stroke-width'] ?? 2) / 2;
		let d;
		if (kind === 'circle') d = Math.abs(Math.hypot(x - a.cx, y - a.cy) - a.r);
		else {
			const dx = a.x2 - a.x1, dy = a.y2 - a.y1;
			const t = Math.max(0, Math.min(1, ((x - a.x1) * dx + (y - a.y1) * dy) / (dx * dx + dy * dy)));
			d = Math.hypot(x - (a.x1 + t * dx), y - (a.y1 + t * dy));
		}
		if (d <= hw) return true;
	}
	return false;
}

function png(w, h, rgba) {
	const crcT = Array.from({ length: 256 }, (_, n) => {
		let c = n;
		for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
		return c >>> 0;
	});
	const crc = (b) => {
		let c = 0xffffffff;
		for (const x of b) c = crcT[(c ^ x) & 255] ^ (c >>> 8);
		return (c ^ 0xffffffff) >>> 0;
	};
	const chunk = (type, data) => {
		const len = Buffer.alloc(4); len.writeUInt32BE(data.length);
		const td = Buffer.concat([Buffer.from(type), data]);
		const c = Buffer.alloc(4); c.writeUInt32BE(crc(td));
		return Buffer.concat([len, td, c]);
	};
	const ihdr = Buffer.alloc(13);
	ihdr.writeUInt32BE(w, 0); ihdr.writeUInt32BE(h, 4); ihdr[8] = 8; ihdr[9] = 6;
	const raw = Buffer.alloc((w * 4 + 1) * h);
	for (let y = 0; y < h; y++) {
		raw[y * (w * 4 + 1)] = 0;
		rgba.copy(raw, y * (w * 4 + 1) + 1, y * w * 4, (y + 1) * w * 4);
	}
	return Buffer.concat([
		Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]),
		chunk('IHDR', ihdr), chunk('IDAT', deflateSync(raw, { level: 9 })), chunk('IEND', Buffer.alloc(0))
	]);
}

// `pad` is the fraction of the canvas left empty on each side; `bg` null = transparent.
export function render(shapeList, size, { fg, bg = null, pad = 0 }) {
	const SS = 8, out = Buffer.alloc(size * size * 4);
	const scale = 24 / (size * (1 - 2 * pad));
	for (let py = 0; py < size; py++)
		for (let px = 0; px < size; px++) {
			let hits = 0;
			for (let sy = 0; sy < SS; sy++)
				for (let sx = 0; sx < SS; sx++) {
					const x = (px + (sx + 0.5) / SS - size * pad) * scale;
					const y = (py + (sy + 0.5) / SS - size * pad) * scale;
					if (covered(shapeList, x, y)) hits++;
				}
			const cov = hits / (SS * SS), o = (py * size + px) * 4;
			const f = rgb(fg);
			if (bg) {
				const b = rgb(bg);
				for (let i = 0; i < 3; i++) out[o + i] = Math.round(f[i] * cov + b[i] * (1 - cov));
				out[o + 3] = 255;
			} else {
				out[o] = f[0]; out[o + 1] = f[1]; out[o + 2] = f[2];
				out[o + 3] = Math.round(cov * 255);
			}
		}
	return png(size, size, out);
}

export function build() {
	const sh = shapes(readFileSync(join(root, 'src/lib/components/Pokeball.svelte'), 'utf8'));
	const { crimson, ink } = readTheme();
	return {
		'static/favicon.svg': Buffer.from(svg(sh, crimson)),
		'static/favicon-32.png': render(sh, 32, { fg: crimson }),
		// iOS paints transparency black and masks the corners itself, so: opaque, padded.
		'static/apple-touch-icon.png': render(sh, 180, { fg: crimson, bg: ink, pad: 0.2 })
	};
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
	const files = build();
	let stale = false;
	for (const [p, buf] of Object.entries(files)) {
		const full = join(root, p);
		if (process.argv.includes('--check')) {
			let cur = null;
			try { cur = readFileSync(full); } catch {}
			if (!cur || !cur.equals(buf)) { console.error(`stale: ${p}`); stale = true; }
		} else writeFileSync(full, buf);
	}
	if (stale) process.exit(1);
}
